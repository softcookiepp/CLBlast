#!/usr/bin/env python3
"""
Compile all GLSL kernels to SPIR-V in parallel, using a JSON manifest.
The manifest is generated by generate_all_kernels.py during CMake configure.

Usage:
    python compile_all_kernels.py <manifest_path>

This reads the manifest, creates the output directory, and compiles all
kernels using concurrent.futures.ProcessPoolExecutor for maximum throughput.
"""
import json
import os
import subprocess
import sys
from concurrent.futures import ProcessPoolExecutor, as_completed


def compile_kernel(kernel_info, glslc_path, output_dir):
    """Compile a single kernel. Returns (name, success) tuple."""
    name = kernel_info["name"]
    source = kernel_info["source"]
    args = kernel_info["args"]
    language = kernel_info["language"]

    if language != "glsl":
        raise NotImplementedError(f"Language {language} not supported")

    if not os.path.exists(source):
        print(f"  [SKIP] {name}: source not found ({source})", file=sys.stderr)
        return name, True  # Skip missing sources gracefully

    spv_path = os.path.join(output_dir, f'{kernel_info["namespace"]}____{name}____{kernel_info["entrypoint"]}.spv')

    # Skip if already compiled (incremental build)
    if os.path.exists(spv_path):
        return name, True

    cmd = [glslc_path, "--target-spv=spv1.5", "-fshader-stage=compute", source]
    cmd.extend(args)
    cmd.extend(["-o", spv_path])

    try:
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
        if result.returncode != 0:
            print(f"  [FAIL] {name}:", file=sys.stderr)
            print(result.stderr, file=sys.stderr)
            return name, False
    except subprocess.TimeoutExpired:
        print(f"  [TIMEOUT] {name}", file=sys.stderr)
        return name, False
    except Exception as e:
        print(f"  [ERROR] {name}: {e}", file=sys.stderr)
        return name, False

    return name, True


def main():
    manifest_path = sys.argv[1]

    with open(manifest_path, "r") as f:
        manifest = json.load(f)

    glslc_path = manifest["glslc"]
    output_dir = manifest["output_dir"]
    kernels = manifest["kernels"]

    if not kernels:
        print("No kernels to compile.")
        return 0

    # Create output directory
    os.makedirs(output_dir, exist_ok=True)

    print(f"Compiling {len(kernels)} kernels in parallel (glslc: {glslc_path})...")

    # Determine parallelism: use CPU count but cap at a reasonable number
    max_workers = min(os.cpu_count() or 4, 16)

    failed = []
    with ProcessPoolExecutor(max_workers=max_workers) as executor:
        futures = {
            executor.submit(compile_kernel, kernel, glslc_path, output_dir): kernel["name"]
            for kernel in kernels
        }
        completed = 0
        total = len(futures)
        for future in as_completed(futures):
            name, success = future.result()
            completed += 1
            if completed % 100 == 0 or completed == total:
                print(f"  Progress: {completed}/{total} kernels compiled")
            if not success:
                failed.append(name)

    if failed:
        print(f"\n{len(failed)} kernels failed to compile:", file=sys.stderr)
        for name in failed:
            print(f"  - {name}", file=sys.stderr)
        return 1

    print(f"\nAll {total} kernels compiled successfully.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
