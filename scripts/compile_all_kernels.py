#!/usr/bin/env python3
"""
Compile all GLSL kernels to SPIR-V and generate C++ headers using tart-spirv-inliner.
The manifest is generated by generate_all_kernels.py during CMake configure.

Usage:
    python compile_all_kernels.py <manifest_path> <tart_spirv_inliner_path>

This reads the manifest, builds a single command line for tart-spirv-inliner with all
kernel inputs (namespaces, source files, and compiler args), and invokes the inliner
once to compile all shaders and generate the combined C++ header files.
"""
import json
import os
import subprocess
import sys


def main():
    manifest_path = sys.argv[1]
    inliner_path = sys.argv[2]

    with open(manifest_path, "r") as f:
        manifest = json.load(f)

    output_dir = manifest["output_dir"]
    kernels = manifest["kernels"]

    if not kernels:
        print("No kernels to compile.")
        return 0

    # Remove placeholder files before checking (they were created at configure time)
    output_hpp = os.path.join(output_dir, "all-blas-kernels.hpp")
    output_cpp = os.path.join(output_dir, "all-blas-kernels.cpp")
    for f_path in [output_hpp, output_cpp]:
        if os.path.exists(f_path):
            with open(f_path, "r") as check:
                content = check.read()
                if content.strip().startswith("// Placeholder"):
                    os.remove(f_path)

    # Check if .compiled marker exists (survives rm between CMake commands)
    compiled_marker = manifest_path + ".compiled"
    if os.path.exists(compiled_marker):
        # Check if output files are valid (not empty/placeholder)
        hpp_ok = os.path.exists(output_hpp) and os.path.getsize(output_hpp) > 100
        cpp_ok = os.path.exists(output_cpp) and os.path.getsize(output_cpp) > 100
        if hpp_ok and cpp_ok:
            print("Kernels already compiled, skipping.")
            return 0
        # Marker exists but files are missing/empty - will regenerate below
        print("Compiling kernels (marker exists but output missing)...")

    # Create output directory
    os.makedirs(output_dir, exist_ok=True)

    # Build the command line for tart-spirv-inliner
    cmd = [inliner_path, "--output", os.path.join(output_dir, "all-blas-kernels")]

    for kernel in kernels:
        source = kernel["source"]
        namespace = kernel["namespace"]
        name = kernel.get("name")

        # Skip missing sources gracefully
        if not os.path.exists(source):
            print(f"  [SKIP] {name or os.path.basename(source)}: source not found ({source})",
                  file=sys.stderr)
            continue

        cmd.append("--namespace")
        cmd.append(namespace)
        cmd.append("--name")
        cmd.append(name)
        cmd.append("--input")
        cmd.append(source)

        # Add compiler args (both explicit --compiler-arg and raw -D args)
        for arg in kernel.get("args", []):
            if arg.startswith("--compiler-arg"):
                cmd.append("--compiler-arg")
                cmd.append(arg.split("=", 1)[1] if "=" in arg else arg)
            elif arg.startswith("-"):
                cmd.append(arg)

        # Add SPIR-V 1.3+ target for subgroup operation support (required by some shaders)
        cmd.append("--target-env=vulkan1.3")

    print(f"Compiling {len(kernels)} kernels via tart-spirv-inliner...")
    print(f"  Command: {' '.join(cmd[:5])}... ({len(cmd)} total args)")

    try:
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=600)
        if result.stdout:
            print(result.stdout)
        if result.returncode != 0:
            print(f"  [FAIL] tart-spirv-inliner:", file=sys.stderr)
            print(result.stderr, file=sys.stderr)
            return 1
    except subprocess.TimeoutExpired:
        print(f"  [TIMEOUT] tart-spirv-inliner", file=sys.stderr)
        return 1
    except Exception as e:
        print(f"  [ERROR] tart-spirv-inliner: {e}", file=sys.stderr)
        return 1

    print(f"\nAll kernels compiled and headers generated successfully.")

    # Create the .compiled marker file so CMake doesn't re-run
    compiled_marker = manifest_path + ".compiled"
    with open(compiled_marker, "w") as f:
        f.write("compiled\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())
